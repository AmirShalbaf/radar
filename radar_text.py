#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
radar_text.py — کمک‌تابع‌های متن فارسی، تنها منبع اصلی
=======================================================

چرا پیمانه جدا
--------------
تابع `fa` اول در `radar_state.py` نوشته شد. دومین مصرف‌کننده که پیدا شد
(`radar_snapshot.py`) دو راه داشت: کپی محلی، یا ایمپورت.

کپی محلی همان اشتباهی بود که تازه در دفترچه رویدادها ثبت شده: «متنی که
در دو جا نوشته می‌شود، دیر یا زود از هم جدا می‌افتد.» قاعده برای کد هم
همان است.

ایمپورت از `radar_fetch3.py` — پیمانه مشترک رسمی پروژه — هم درست نبود:
آن فایل pandas و numpy و requests و کل لایه صرافی را می‌آورد. برای یک
تابع سه‌خطی گران است، و استقلال عمدی `radar_levels.py` و
`radar_snapshot.py` و `radar_state.py` و `radar_watch.py` را می‌شکند.

پس این پیمانه **فقط کتابخانه استاندارد** لازم دارد. هر اسکریپتی
می‌تواند بی‌هزینه ایمپورتش کند.

قاعده رقم فارسی
---------------
هر عددی فارسی نمی‌شود. تفکیک:

| دسته | مثال | رقم |
|---|---|---|
| نثر و آستانه و شماره نسخه | «آستانه ۱۴ روز»، «رادار ۶.۱» | فارسی |
| داده بازار | قیمت ۹۳.۸۱، حجم ۶۲٬۰۰۰ دلار | لاتین |
| فرمول و رد محاسبه | `۲.۰ × ۰.۳۰ = ۰.۶۰` | لاتین |
| شناسه ماشین و مهر زمانی و نام فایل | `v6.1`، `2026-09-15` | لاتین |

دلیل نگه‌داشتن داده بازار به لاتین: در جدول کنار هم می‌نشینند و با
رقم فارسی مقایسه چشمی سخت می‌شود. ثابت `FRAMEWORK` در `radar_fetch3.py`
از ابتدا «۵.۴» فارسی بود — همان قرارداد، اینجا صریح شد.

تله عبارت باقاعده
-----------------
در پایتون `\\d` **رقم فارسی را هم می‌گیرد**، چون هر دو در رده یونیکد
`Nd` هستند. همین برای `\\w` و `\\b` هم صادق است: `\\w` حرف فارسی و رقم
فارسی هر دو را می‌پذیرد.

این رفتار گاهی همان چیزی است که می‌خواهی و گاهی تله:

* **می‌خواهی** — `radar_intake.py` و `radar_digest.py` عدد را داخل متن
  فارسی تحلیل‌گر پیدا می‌کنند. آنجا «۶۲ هزار» باید تطبیق کند. دست نزن.
* **تله** — وقتی الگو باید فقط اسکی بگیرد: شناسه ویدئوی یوتیوب، شناسه
  کانال، نماد صرافی، شماره نسخه داخل کد. آنجا `[0-9]` و
  `[A-Za-z0-9_-]` بنویس، نه `\\d` و `\\w`.

قاعده: اگر دامنه ورودی اسکی است، الگو هم اسکی باشد.
"""

from __future__ import annotations

__all__ = ["FA_DIGITS", "EN_DIGITS", "fa", "en"]

# سه مجموعه رقم، سه بازه یونیکد جدا:
#   لاتین            0-9        U+0030
#   فارسی            ۰-۹        U+06F0   (Extended Arabic-Indic)
#   عربی             ٠-٩        U+0660   (Arabic-Indic)
#
# فارسی و عربی نویسه‌های متفاوتی‌اند، نه دو نمایش از یک نویسه. متن
# رونویسی‌شده خودکار هر دو را می‌دهد، پس تبدیل به لاتین باید هر دو را
# بگیرد. این تفکیک اول در `radar_intake.py` کشف شده بود؛ اینجا منبع
# اصلی شد تا دوباره جدا نیفتد.
_LATIN = "0123456789"
_PERSIAN = "۰۱۲۳۴۵۶۷۸۹"
_ARABIC = "٠١٢٣٤٥٦٧٨٩"

# خروجی: فقط لاتین به فارسی. برای نوشتن متن فارسی.
FA_DIGITS = str.maketrans(_LATIN, _PERSIAN)

# ورودی: هر دو خانواده شرقی به لاتین. برای تجزیه متن دریافتی.
EN_DIGITS = {ord(c): l for c, l in zip(_PERSIAN, _LATIN)}
EN_DIGITS.update({ord(c): l for c, l in zip(_ARABIC, _LATIN)})


def fa(s) -> str:
    """
    هر رقم لاتین به رقم فارسی. بقیه نویسه‌ها دست‌نخورده می‌مانند.

        fa("6.1")        → "۶.۱"
        fa(14)           → "۱۴"
        fa("7.0-p1")     → "۷.۰-p۱"

    توجه به نمونه سوم: تابع **همه** ارقام را می‌گیرد، حتی داخل یک
    شناسه مثل «p1». اگر بخشی باید لاتین بماند، آن بخش را جدا نگه دار
    و `fa` را فقط روی بخش فارسی بزن.
    """
    return str(s).translate(FA_DIGITS)


def en(s) -> str:
    """
    رقم فارسی یا عربی به لاتین — برای تجزیه متن دریافتی.

        en("۱۴")         → "14"
        en("٤٢")         → "42"

    لازم است چون عبارت باقاعده اسکی (`[0-9]`) رقم شرقی را نمی‌گیرد، و
    `float("۱۴.۵")` هم خطا می‌دهد — گرچه `int("۱۴")` کار می‌کند.
    """
    return str(s).translate(EN_DIGITS)
